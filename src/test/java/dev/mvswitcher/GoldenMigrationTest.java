package dev.mvswitcher;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.io.IOException;
import java.nio.file.*;
import java.util.ArrayList;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;

/**
 * Golden tests for the bundled rules. Every case lives in
 * {@code src/test/resources/golden/<from>/<to>/<case>/} with an {@code input/} tree (the mod sources in the
 * source version) and an {@code expected/} tree (the files as they must look after migration). A new case needs
 * no Java: add the two folders. Build metadata is generated by the test, so the folders hold only the sources.
 */
class GoldenMigrationTest {
    @TempDir Path temp;

    record Case(String from, String to, String name, Path dir) {}

    private static Path goldenRoot() throws Exception {
        var url = GoldenMigrationTest.class.getResource("/golden");
        assertNotNull(url);
        return Path.of(url.toURI());
    }

    private static List<Case> cases() throws Exception {
        Path root = goldenRoot();
        List<Case> result = new ArrayList<>();
        try (var paths = Files.walk(root, 3)) {
            paths.filter(p -> Files.isDirectory(p) && root.relativize(p).getNameCount() == 3).sorted().forEach(p -> {
                Path relative = root.relativize(p);
                result.add(new Case(relative.getName(0).toString(), relative.getName(1).toString(),
                        relative.getName(2).toString(), p));
            });
        }
        return result;
    }

    private static void copyTree(Path source, Path target) throws IOException {
        try (var paths = Files.walk(source)) {
            for (Path path : paths.toList()) {
                Path destination = target.resolve(source.relativize(path).toString());
                if (Files.isDirectory(path)) Files.createDirectories(destination);
                else {
                    Files.createDirectories(destination.getParent());
                    Files.copy(path, destination, StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
    }

    private static String normalized(Path file) throws IOException {
        return Files.readString(file).replace("\r\n", "\n");
    }

    private List<String> run(Case c) throws Exception {
        String label = c.from() + " -> " + c.to() + " / " + c.name();
        List<String> problems = new ArrayList<>();
        Path input = c.dir().resolve("input");
        Path expected = c.dir().resolve("expected");
        if (!Files.isDirectory(input) || !Files.isDirectory(expected)) {
            problems.add(label + ": needs both input/ and expected/ folders");
            return problems;
        }
        String key = (c.from() + "_" + c.to() + "_" + c.name()).replaceAll("[^A-Za-z0-9._-]", "_");
        Path project = temp.resolve("project_" + key);
        copyTree(input, project);
        Files.writeString(project.resolve("build.gradle"), "plugins { id 'net.neoforged.gradle.userdev' }\n");
        Files.writeString(project.resolve("gradle.properties"), "minecraft_version=" + c.from() + "\n");
        Files.createDirectories(project.resolve("src/main/resources/META-INF"));
        Files.writeString(project.resolve("src/main/resources/META-INF/neoforge.mods.toml"), "modLoader=\"javafml\"\n");

        Path output = temp.resolve("output_" + key);
        var report = MigrationEngine.migrate(new MigrationOptions(
                project, c.from(), c.to(), null, null, output, null, null, false, false, true));
        if (report.hasErrors()) problems.add(label + ": migration reported errors:\n" + report.toText());

        List<Path> expectedFiles;
        try (var paths = Files.walk(expected)) {
            expectedFiles = paths.filter(Files::isRegularFile).sorted().toList();
        }
        if (expectedFiles.isEmpty()) problems.add(label + ": expected/ contains no files");
        for (Path file : expectedFiles) {
            String relative = expected.relativize(file).toString().replace('\\', '/');
            Path actual = output.resolve(relative);
            if (!Files.isRegularFile(actual)) {
                problems.add(label + ": missing output file " + relative);
            } else if (!normalized(file).equals(normalized(actual))) {
                problems.add(label + ": " + relative + " differs.\n--- expected ---\n" + normalized(file)
                        + "--- actual ---\n" + normalized(actual));
            }
        }
        return problems;
    }

    @Test void everyGoldenCaseProducesTheExpectedFiles() throws Exception {
        List<Case> cases = cases();
        assertFalse(cases.isEmpty());
        List<String> problems = new ArrayList<>();
        for (Case c : cases) problems.addAll(run(c));
        assertEquals(List.of(), problems);
    }

    @Test void everyBundledEdgeHasAtLeastOneGoldenCase() throws Exception {
        List<Case> cases = cases();
        List<String> missing = new ArrayList<>();
        for (String edge : MigrationEngine.bundledRoutes()) {
            String[] versions = edge.split(" -> ");
            boolean covered = cases.stream().anyMatch(c -> c.from().equals(versions[0]) && c.to().equals(versions[1]));
            if (!covered) missing.add(edge);
        }
        assertEquals(List.of(), missing);
    }
}
